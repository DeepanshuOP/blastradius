"""BM25 (baseline B5, RAG sparse ranking) must not depend on PYTHONHASHSEED (D-64)."""

import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

from tests.conftest import requires_data

ROOT = Path(__file__).resolve().parents[1]
STAMP = re.compile(r"^Generated by .*$", re.MULTILINE)

_SNIPPET = """
from src.eval.baselines import bm25_scores
docs = [
    ["src", "itsdangerous", "timed", "py"], ["tests", "test", "timed", "py"], ["tests", "test", "signer", "py"],
    ["tests", "test", "serializer", "py"], ["docs", "index", "rst"], ["src", "itsdangerous", "signer", "py"],
]
query = ["src", "itsdangerous", "timed", "py", "signer", "tests", "docs", "rst", "index", "test"]
print([repr(float(x)) for x in bm25_scores(docs, query)])
"""


def _run(args: list[str], seed: str) -> str:
    env = {**os.environ, "PYTHONHASHSEED": seed, "BR_OFFLINE": "1"}
    p = subprocess.run(args, cwd=ROOT, env=env, capture_output=True, text=True, check=True)
    return p.stdout


def test_bm25_scores_identical_across_hash_seeds() -> None:
    outs = {s: _run([sys.executable, "-c", _SNIPPET], s) for s in ("0", "1", "2", "3")}
    assert len(set(outs.values())) == 1, outs


@requires_data("data/processed/e1_features.parquet")
def test_rq2_predictor_identical_across_hash_seeds() -> None:
    """Two full `analysis.rq2_predictor` runs (about 15 minutes each); stamp lines are ignored."""
    target = ROOT / "paper/generated/rq2_predictor.md"
    original = target.read_bytes() if target.exists() else None
    texts: dict[str, str] = {}
    try:
        for seed in ("0", "1"):
            _run([sys.executable, "-m", "analysis.rq2_predictor"], seed)
            texts[seed] = STAMP.sub("", target.read_text(encoding="utf-8"))
    finally:
        if original is not None:
            target.write_bytes(original)
    assert texts["0"] == texts["1"]
